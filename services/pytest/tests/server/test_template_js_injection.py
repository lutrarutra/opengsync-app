"""Template values must not be spliced into JavaScript/hyperscript string literals.

Regression for the customer test 2026-11-04: a seq request named ``x' + alert(1) + '`` ran script when
its Submit button was clicked. In an HTML attribute (``_="..."``, ``onclick="..."``) the browser decodes
Jinja's ``&#39;`` back to ``'`` before hyperscript/JS parses it, so autoescaping does not help. Values go
in as one string literal instead: ``{{ (... ~ value ~ ...) | hs_string }}`` in hyperscript, ``| tojson`` in
JavaScript. (Hyperscript does not decode JSON's ``\\u0027`` escapes, so ``tojson`` shows garbled text there.)
"""
import html
import re
from pathlib import Path

from fastapi.testclient import TestClient

from opengsync_db import SyncSession

from ..db.create_units import create_seq_request, create_pool
from ._http import get

# Values that are generated by the server, never by users (ids, routes, constants, field names).
SAFE_EXPRESSION = re.compile(
    r"tojson|hs_string|url_for|_url\b|\burl\b|\.id\b|_id\b|\|\s*(int|float)\b|csrf|loop\.index|\.uuid\b"
    r"|\bguid\b|\buid\b|\blane\b|\bid\b|\btoday\b|\bicon\b|\bentity(_name)?\b"
    r"|\bfield\.name\b|\bform\.\w+\.name\b|\bextra\.name\b|\bC\.\w+"
)
JINJA = re.compile(r"\{\{.*?\}\}|\{%.*?%\}|\{#.*?#\}", re.S)
HYPERSCRIPT = re.compile(r"""\s_=(["'])(.*?)\1(?=[\s>/])""", re.S)
ATTRIBUTE = re.compile(r"""(?:\s_|\son[a-z]+|\shx-on[:\w-]*)=(["'])(.*?)\1(?=[\s>/])""", re.S)
SCRIPT = re.compile(r"<script\b[^>]*>(.*?)</script>", re.S)


def _expressions_in_js_strings(body: str):
    """Yield (offset, expression) of every ``{{ }}`` that sits inside a JS string literal of ``body``."""
    i, quote = 0, None
    while i < len(body):
        if body[i] == "{" and body[i + 1:i + 2] in ("{", "%", "#"):
            if (m := JINJA.match(body, i)) is None:
                i += 2
                continue
            if quote and body[i + 1] == "{":
                yield i, m.group(0)
            i = m.end()
            continue
        c = body[i]
        if quote:
            if c == "\\":
                i += 2
                continue
            if c == quote:
                quote = None
        elif c in "'\"`":
            quote = c
        elif body.startswith("//", i) and body[i - 1:i] != ":":  # line comment, not a URL
            i = j if (j := body.find("\n", i)) >= 0 else len(body)
            continue
        i += 1


def _violations(root: Path) -> list[str]:
    found = []
    for path in sorted(root.rglob("*")):
        if path.suffix not in (".html", ".jinja2"):
            continue
        src = path.read_text(errors="ignore")
        contexts = [(m.start(2), m.group(2)) for m in ATTRIBUTE.finditer(src)]
        contexts += [(m.start(1), m.group(1)) for m in SCRIPT.finditer(src)]
        for start, body in contexts:
            for offset, expr in _expressions_in_js_strings(body):
                if not SAFE_EXPRESSION.search(expr):
                    line = src[:start + offset].count("\n") + 1
                    found.append(f"{path.relative_to(root)}:{line}: {expr}")
    return found


def test_no_template_value_inside_js_string_literal(client: TestClient):
    from server.core.templates import j2

    assert _violations(Path(j2.env.loader.searchpath[0])) == []  # type: ignore[union-attr]


def test_hyperscript_does_not_use_tojson(client: TestClient):
    from server.core.templates import j2

    root = Path(j2.env.loader.searchpath[0])  # type: ignore[union-attr]
    found = []
    for path in sorted(root.rglob("*")):
        if path.suffix in (".html", ".jinja2"):
            src = path.read_text(errors="ignore")
            for m in HYPERSCRIPT.finditer(src):
                if "tojson" in m.group(2):
                    found.append(f"{path.relative_to(root)}:{src[:m.start()].count(chr(10)) + 1}")
    assert found == [], "use | hs_string in hyperscript"


def test_lint_catches_the_original_pattern():
    body = """title: 'Submit request \\'{{ form.seq_request.name }}\\'', text: {{ x | tojson }}"""
    assert [expr for _, expr in _expressions_in_js_strings(body)] == ["{{ form.seq_request.name }}"]


# ── rendered pages: the payload stays one closed JSON string ──────────────────

PAYLOAD = "x' + alert(1) + '"


def _hyperscript_attributes(page: str) -> list[str]:
    return [html.unescape(v) for v in re.findall(r'\s_="(.*?)"(?=[\s>/])', page, re.S)]


def _assert_string_literal(page: str, text: str):
    literal = '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'  # what `| hs_string` emits
    assert any(literal in attr for attr in _hyperscript_attributes(page)), f"{literal} not found as a literal"
    # the payload only occurs inside that literal, never as hyperscript code
    without_strings = [re.sub(r'"(?:[^"\\]|\\.)*"', '""', attr) for attr in _hyperscript_attributes(page)]
    assert not any("alert(1)" in attr for attr in without_strings)


def test_submit_button_title_is_a_string_literal(client: TestClient, session: SyncSession, user, user_token: str):
    seq_request = create_seq_request(session, user)
    seq_request.name = PAYLOAD
    session.save(seq_request, flush=True)
    session.commit()

    response = get(client, f"/htmx/seq_requests/{seq_request.id}/submit", user_token, htmx=True)
    assert response.status_code == 200
    _assert_string_literal(response.text, f"Submit request '{PAYLOAD}'")


def test_pool_page_titles_are_string_literals(client: TestClient, session: SyncSession, insider, insider_token: str):
    pool = create_pool(session, insider, create_seq_request(session, insider))
    pool.name = PAYLOAD
    session.save(pool, flush=True)
    session.commit()

    response = get(client, f"/pools/{pool.id}", insider_token)
    assert response.status_code == 200
    _assert_string_literal(response.text, f"Delete Pool '{PAYLOAD}'")


def test_hs_string_escapes_only_backslash_and_quote():
    """Hyperscript escapes, then HTML-escaped for the attribute (macros in .jinja2 files used to be unescaped)."""
    from server.core.templates import hs_string
    rendered = str(hs_string("a 'b' \\ \"c\"\nd <x>"))
    assert "'" not in rendered and "<" not in rendered  # safe in a single-quoted attribute
    assert html.unescape(rendered) == '"a \'b\' \\\\ \\"c\\" d <x>"'


