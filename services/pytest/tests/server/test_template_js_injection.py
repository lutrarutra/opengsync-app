def _swal_configs(src: str):
    for m in re.finditer(r"Swal\.fire\(\{", src):
        depth, j = 1, m.end()
        while j < len(src) and depth:
            depth += {"{": 1, "}": -1}.get(src[j], 0)
            j += 1
        yield m.start(), src[m.end():j]


def test_swal_dialogs_use_text_titles(client: TestClient):
    """SweetAlert2 renders ``title`` (and ``html``) as HTML: a request named <img onerror=...> ran script in its
    Submit confirmation (customer test 2026-11-04). Titles go in ``titleText``, which is plain text."""
    from server.core.templates import j2

    roots = [Path(j2.env.loader.searchpath[0])]  # type: ignore[union-attr]
    roots.append(roots[0].parent / "static" / "js")
    found = []
    for root in roots:
        for path in sorted(root.rglob("*")):
            if path.suffix not in (".html", ".jinja2", ".js") or ".min." in path.name:
                continue
            src = path.read_text(errors="ignore")
            for start, config in _swal_configs(src):
                # html is allowed for a DOM element built with textContent (flash toasts; errors/error.html)
                if re.search(r"(?<![\w.])title\s*:|(?<![\w.])html\s*:(?!\s*(flashToastContent\(|content,))", config):
                    found.append(f"{path.name}:{src[:start].count(chr(10)) + 1}")
    assert found == [], "use titleText/text in Swal.fire (html only for trusted markup)"


